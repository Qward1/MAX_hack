def _items(lines: tuple[str, ...]) -> str:
    return "<ul>" + "".join(f"<li>{escape(line)}</li>" for line in lines) + "</ul>"


def render_privacy_page(*, contact: str | None, site_url: str) -> str:
    """HTML страницы. Все тексты — константы модуля, экранированные."""
    service = (
        CONTACT_SERVICE.format(contact=contact.strip())
        if contact and contact.strip()
        else CONTACT_SERVICE_UNSET.format(site=site_url)
    )
    rows = "".join(
        f'<tr><th scope="row">{escape(what)}</th><td>{escape(how)}</td></tr>'
        for what, how in STORES
    )
    return (
        '<!doctype html><html lang="ru"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        f"<title>{escape(PRIVACY_TITLE)}</title><style>{_STYLE}</style></head>"
        f"<body><main><h1>{escape(PRIVACY_TITLE)}</h1>"
        f"<p>{escape(INTRO)}</p>"
        f"<h2>{escape(READS_TITLE)}</h2>{_items(READS)}"
        f"<h2>{escape(STORES_TITLE)}</h2><table><tbody>{rows}</tbody></table>"
        f"<h2>{escape(MODEL_TITLE)}</h2>{_items(MODEL)}"
        f"<h2>{escape(OFF_TITLE)}</h2>{_items(OFF)}"
        f"<h2>{escape(CONTACT_TITLE)}</h2>{_items((CONTACT_HOUSE, service))}"
        f'<p class="muted">{escape(REVISION)}</p></main></body></html>'
    )


