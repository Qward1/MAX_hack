def privacy_url(public_base_url: str | None) -> str:
    """Адрес страницы: абсолютный при известном адресе сервиса, иначе путь."""
    base = (public_base_url or "").strip().rstrip("/")
    return f"{base}{PRIVACY_PATH}" if base else PRIVACY_PATH


def with_privacy(text: str, url: str) -> str:
    """Текст сообщения бота со строкой-ссылкой на страницу данных."""
    return f"{text}\n\n{PRIVACY_LINE.format(url=url)}"


